export const SHOP_UNLOCK_ORDER = STREET_SHOPS.map((shop) => shop.id);

export const getShopPrerequisite = (shopId: string): StreetShop | null => {
  const index = SHOP_UNLOCK_ORDER.indexOf(shopId);
  const previousId = index > 0 ? SHOP_UNLOCK_ORDER[index - 1] : null;
  return previousId ? STREET_SHOPS.find((shop) => shop.id === previousId) || null : null;
};

export const getShopUpgradeCost = (shop: StreetShop, currentLevel: number): number =>
  Math.round(Math.max(20000, shop.unlockCost * 0.6) * Math.pow(1.7, currentLevel - 1));

export const getShopUpgradeRequiredLevel = (shop: StreetShop, currentLevel: number): number =>
  shop.requiredLevel + currentLevel;

export const getRequiredReputationForShop = (shop: StreetShop): number => {
  if (shop.streetScreen >= 7) return 4.5;
  if (shop.streetScreen >= 4) return 4.0;
  if (shop.streetScreen >= 2) return 3.5;
  return 3.0;
};

export const getRequiredCartTierForShop = (shop: StreetShop): number => {
  if (shop.streetScreen >= 8) return 4;
  if (shop.streetScreen >= 6) return 3;
  if (shop.streetScreen >= 3) return 2;
  return 1;
};

export const SHOP_MAP: Record<string, StreetShop> = STREET_SHOPS.reduce((acc, curr) => {
  acc[curr.id] = curr;
  return acc;
}, {} as Record<string, StreetShop>);
